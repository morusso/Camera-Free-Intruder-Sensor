#!/usr/bin/env python3
"""Turn model_int8.tflite into a C array for the RX firmware (step 4.2).

Writes firmware/rx/components/csi_model/model_data.c with
  - the model as a 16-byte aligned const array (stays in flash),
  - a golden test: the output of the TFLite reference interpreter for a fixed, formula-defined input
    (see GOLDEN_INPUT below), so the device can check that ESP-NN gives the same result.

It also checks that every operator of the model is registered in the firmware's op resolver
(csi_model.cpp), so a model with an unsupported layer is rejected here and not at boot.

Example:
    python ml/tflite_to_c.py ml/runs/20261112_cnn_s0/model_int8.tflite
"""
from __future__ import annotations

from pathlib import Path
from typing import List

import numpy as np
import typer

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "firmware" / "rx" / "components" / "csi_model" / "model_data.c"

# Keep in sync with the resolver in csi_model.cpp (test_tflite_to_c.py checks that).
SUPPORTED_OPS = ["EXPAND_DIMS", "CONV_2D", "RESHAPE", "MEAN", "FULLY_CONNECTED", "SOFTMAX"]


def golden_input(n: int) -> np.ndarray:
    """int8 test input, defined by a formula so the firmware does not need to store it."""
    i = np.arange(n, dtype=np.int64)
    return (((i * 37 + 11) % 255) - 127).astype(np.int8)


def model_ops(tflite_bytes: bytes) -> List[str]:
    from arena import buffers_from_tflite
    return buffers_from_tflite(tflite_bytes)[1]


def golden_output(tflite_bytes: bytes) -> np.ndarray:
    import tensorflow as tf
    interp = tf.lite.Interpreter(
        model_content=tflite_bytes,
        experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    x = golden_input(int(np.prod(inp["shape"]))).reshape(inp["shape"])
    interp.set_tensor(inp["index"], x)
    interp.invoke()
    return interp.get_tensor(out["index"]).reshape(-1)


def render(tflite_bytes: bytes, source: str) -> str:
    unsupported = sorted(set(model_ops(tflite_bytes)) - set(SUPPORTED_OPS))
    if unsupported:
        raise ValueError(f"operators not registered in the firmware: {unsupported}; add them to csi_model.cpp "
                         f"and SUPPORTED_OPS")
    golden = golden_output(tflite_bytes)

    rows = []
    for i in range(0, len(tflite_bytes), 16):
        rows.append("    " + ",".join(f"0x{b:02x}" for b in tflite_bytes[i:i + 16]) + ",")
    return (
        f"/* GENERATED by ml/tflite_to_c.py from {source}. DO NOT EDIT. */\n"
        '#include "csi_model.h"\n\n'
        f"const unsigned char csi_model_data[] __attribute__((aligned(16))) = {{\n" + "\n".join(rows) + "\n};\n"
        f"const unsigned int csi_model_data_len = {len(tflite_bytes)};\n\n"
        f"const signed char csi_model_golden_out[{len(golden)}] = {{"
        + ", ".join(str(int(v)) for v in golden) + "};\n"
        f"const unsigned int csi_model_golden_out_len = {len(golden)};\n"
    )


app = typer.Typer(add_completion=False, help="Convert a .tflite model to a C array for the firmware.")


@app.command()
def main(
    tflite: Path = typer.Argument(..., exists=True, dir_okay=False),
    out: Path = typer.Option(DEFAULT_OUT, help="Output .c file."),
) -> None:
    data = tflite.read_bytes()
    try:
        text = render(data, tflite.name)
    except ValueError as e:
        typer.echo(f"Error: {e}", err=True)
        raise typer.Exit(1)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    typer.echo(f"{len(data) / 1024:.1f} KB model written to {out}")


if __name__ == "__main__":
    app()
