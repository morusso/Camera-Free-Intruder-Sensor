#!/usr/bin/env python3
"""Generate firmware/common/include/preprocess_params.h from preprocess_config.json.

The firmware must use the very same numbers as ml/preprocess.py, so the header is generated, never edited by
hand. test_preprocess_c.py fails if the committed header is out of date.

    python ml/gen_preprocess_header.py
"""
from __future__ import annotations

from pathlib import Path

from scipy import signal

from preprocess import PreprocessConfig

HEADER_PATH = Path(__file__).resolve().parents[1] / "firmware" / "common" / "include" / "preprocess_params.h"


def render(cfg: PreprocessConfig) -> str:
    sos = signal.butter(cfg.lowpass_order, cfg.lowpass_cutoff_hz, fs=cfg.sample_rate_hz, output="sos")
    zi = signal.sosfilt_zi(sos)
    f = lambda v: f"{float(v):.9e}f"  # noqa: E731  (9 digits round-trip a float32)

    cont = " \\\n"  # macro line continuation
    sos_rows = cont.join("    {" + ", ".join(f(v) for v in row) + "}," for row in sos)
    zi_rows = cont.join("    {" + ", ".join(f(v) for v in row) + "}," for row in zi)
    keep = ", ".join(str(i) for i in cfg.keep_subcarriers)
    return f"""/* GENERATED by ml/gen_preprocess_header.py from ml/preprocess_config.json. DO NOT EDIT. */
#pragma once

#define CSI_PP_N_VALUES        {cfg.n_values}   /* int8 values per CSI frame (imag, real, ...) */
#define CSI_PP_N_KEEP          {len(cfg.keep_subcarriers)}   /* subcarriers kept after dropping null/pilot/guard */
#define CSI_PP_HAMPEL_HALF     {cfg.hampel_half_window}
#define CSI_PP_HAMPEL_WIN      {2 * cfg.hampel_half_window + 1}
#define CSI_PP_HAMPEL_NSIGMA   {f(cfg.hampel_n_sigma)}
#define CSI_PP_HAMPEL_MIN_SCALE {f(cfg.hampel_min_scale)}
#define CSI_PP_NORM_MIN_STD    {f(cfg.norm_min_std)}
#define CSI_PP_N_SECTIONS      {len(sos)}   /* second-order sections of the low-pass */

/* Indices into the n_values/2 subcarriers of a frame. */
#define CSI_PP_KEEP_INIT {{{keep}}}

/* Butterworth low-pass, rows are {{b0, b1, b2, a0, a1, a2}} (scipy sos layout, a0 == 1). */
#define CSI_PP_SOS_INIT {{ \\
{sos_rows} \\
}}

/* Steady-state filter registers for a unit step, per section: start the filter at x0 with z = zi * x0. */
#define CSI_PP_ZI_INIT {{ \\
{zi_rows} \\
}}
"""


def main() -> None:
    HEADER_PATH.write_text(render(PreprocessConfig.load()))
    print(f"wrote {HEADER_PATH}")


if __name__ == "__main__":
    main()
